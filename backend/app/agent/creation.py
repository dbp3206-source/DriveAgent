"""Typed, inert creation proposals. A proposal is never a write approval.

Keep these schemas separate from execution payloads: operation IDs, approval
digests and request keys are generated by the application, not by the model.
"""

import json
import re
import unicodedata
from difflib import SequenceMatcher
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field

from app.services.document_creator import DocumentSpec
from app.services.sheet_creator import (
    SheetFormula,
    SheetRowFormula,
    SheetTab,
    SpreadsheetEditIntent,
    SpreadsheetSpec,
)
from app.tools.documents import DocumentEditIntent


class DocumentProposal(BaseModel):
    model_config = ConfigDict(extra="forbid")
    kind: Literal["document"]
    document: DocumentSpec


class SpreadsheetProposal(BaseModel):
    model_config = ConfigDict(extra="forbid")
    kind: Literal["spreadsheet"]
    spreadsheet: SpreadsheetSpec


class DocumentEditProposal(BaseModel):
    model_config = ConfigDict(extra="forbid")
    kind: Literal["document_edit"]
    document_edit: DocumentEditIntent


class SpreadsheetEditProposal(BaseModel):
    model_config = ConfigDict(extra="forbid")
    kind: Literal["spreadsheet_edit"]
    spreadsheet_edit: SpreadsheetEditIntent


class CreationAnswer(BaseModel):
    model_config = ConfigDict(extra="forbid")
    answer: str = Field(min_length=1, max_length=40000)
    proposals: list[
        DocumentProposal
        | SpreadsheetProposal
        | DocumentEditProposal
        | SpreadsheetEditProposal
    ] = Field(default_factory=list, max_length=4)


class WireProposal(BaseModel):
    model_config = ConfigDict(extra="forbid")
    kind: Literal[
        "document",
        "spreadsheet",
        "document_edit",
        "spreadsheet_edit",
    ]
    spec_json: str = Field(min_length=2, max_length=500000)


class WireAnswer(BaseModel):
    """Shallow provider envelope; strictly validate each decoded artifact locally.

    The live Gemini provider rejected the nested grid/union schema with HTTP 400.
    JSON text payloads keep the transport shallow, not the execution validation weak.
    """

    model_config = ConfigDict(extra="forbid")
    answer: str = Field(min_length=1, max_length=40000)
    proposals: list[WireProposal] = Field(default_factory=list, max_length=4)

    @staticmethod
    def provider_schema() -> dict:
        # No refs/deep union grammar; bounds are still enforced by Pydantic below.
        return {
            "type": "object",
            "additionalProperties": False,
            "properties": {
                "answer": {"type": "string"},
                "proposals": {
                    "type": "array",
                    "maxItems": 4,
                    "items": {
                        "type": "object",
                        "additionalProperties": False,
                        "properties": {
                            "kind": {
                                "type": "string",
                                "enum": [
                                    "document", "spreadsheet",
                                    "document_edit", "spreadsheet_edit",
                                ],
                            },
                            "spec_json": {"type": "string"},
                        },
                        "required": ["kind", "spec_json"],
                    },
                },
            },
            "required": ["answer", "proposals"],
        }

    def validate_artifacts(self, *, blank_unsourced_sheet: bool = False) -> CreationAnswer:
        proposals = []
        only_spreadsheets = bool(self.proposals) and all(
            item.kind == "spreadsheet" for item in self.proposals
        )
        for item in self.proposals:
            spec = json.loads(item.spec_json)
            if blank_unsourced_sheet and only_spreadsheets and isinstance(spec, dict):
                # A structural blank-template request provides no transaction
                # records. Discard generated preview rows before validating their
                # shapes; the preview grounder adds the reviewed blank/formula rows.
                # Sourced or sample-data requests never take this path.
                tabs = spec.get("tabs")
                if isinstance(tabs, list):
                    for tab in tabs:
                        if isinstance(tab, dict) and isinstance(tab.get("headers"), list):
                            tab["rows"] = [[None] * len(tab["headers"])]
                            tab["chart"] = None
            proposals.append({"kind": item.kind, item.kind: spec})
        return CreationAnswer(
            answer=self.answer,
            proposals=proposals,
        )


def _sheet_request_data_flags(request: str) -> tuple[bool, bool]:
    """Identify supplied values and explicitly requested illustrative records."""

    explicit_data = bool(
        re.search(r"\|[^|\n]+\|[^|\n]+\|", request)
        or re.search(r"\b\d+(?:[.,]\d+)?\s*(?:₫|đ|vnd|usd|nghìn|triệu)\b", request, re.I)
        or re.search(r"\b\d{5,}\b", request)
        or len(re.findall(r"\b\d{3,}(?:[.,]\d+)?\b", request)) >= 2
    )
    sample_requested = bool(
        re.search(
            r"\b(?:dữ liệu mẫu|giao dịch mẫu|dòng dữ liệu mẫu|"
            r"ví dụ (?:vài |một )?(?:dòng|giao dịch|khoản chi)|"
            r"(?:dữ liệu|giao dịch|dòng) minh họa)\b",
            request,
            re.I,
        )
    ) and not re.search(r"\b(?:mẫu trống|không có dữ liệu)\b", request, re.I)
    return explicit_data, sample_requested


def blank_unsourced_sheet_requested(request: str, *, has_source_data: bool) -> bool:
    """True only for a structural sheet request without supplied/example rows."""

    explicit_data, sample_requested = _sheet_request_data_flags(request)
    return not has_source_data and not explicit_data and not sample_requested


def preserve_explicit_literals(request: str, answer: CreationAnswer) -> CreationAnswer:
    """Restore request text when the model changed only case or accents.

    This is deliberately conservative: a complete generated string is replaced
    only when it matches one contiguous request phrase after Unicode accent
    folding. Missing or semantically different content is never invented.
    """

    if not request.strip() or not answer.proposals:
        return answer

    def folded(value: str) -> str:
        decomposed = unicodedata.normalize("NFKD", value)
        plain = "".join(char for char in decomposed if not unicodedata.combining(char))
        # Vietnamese đ/Đ does not decompose under NFKD.
        plain = plain.translate(str.maketrans({"đ": "d", "Đ": "D"}))
        return " ".join(plain.casefold().split())

    def ascii_signature(value: str) -> str:
        # ASCII letters normally survive this provider mojibake pattern while
        # multibyte Vietnamese characters turn into CJK/private-use glyphs.
        return "".join(char.casefold() for char in value if char.isascii() and char.isalpha())

    def suspicious(value: str) -> bool:
        return any(
            "\u3400" <= char <= "\u9fff" or "\ue000" <= char <= "\uf8ff"
            for char in value
        )

    # Single tokens and short n-grams cover titles, labels, table cells, codes and
    # list items that users commonly specify without quoting every field.
    tokens = list(re.finditer(r"(?u)\b[\w-]+\b", request))
    by_folded: dict[str, str] = {}
    phrase_candidates: list[str] = []
    for start in range(len(tokens)):
        for end in range(start, min(start + 12, len(tokens))):
            phrase = request[tokens[start].start() : tokens[end].end()].strip()
            phrase_candidates.append(phrase)
            by_folded.setdefault(folded(phrase), phrase)
    # Quoted strings are the strongest source of exact surface text.
    strong_literals: set[str] = set()
    for literal in re.findall(r'["“]([^"”]{1,500})["”]', request):
        if literal.strip():
            by_folded[folded(literal)] = literal.strip()
            strong_literals.add(literal.strip())
            phrase_candidates.append(literal.strip())
    phrases = list(dict.fromkeys(phrase_candidates))

    def restore(value: Any, *, table_literal: bool = False) -> Any:
        if isinstance(value, str):
            normalized = folded(value)
            exact = by_folded.get(normalized)
            if exact:
                if table_literal:
                    exact_surfaces = list(
                        dict.fromkeys(
                            candidate
                            for candidate in phrases
                            if folded(candidate) == normalized
                            and len(candidate.split()) == len(value.split())
                        )
                    )
                    title_surfaces = [
                        candidate
                        for candidate in exact_surfaces
                        if candidate[:1].isupper()
                    ]
                    if value[:1].islower() and len(title_surfaces) == 1:
                        return title_surfaces[0]
                return exact
            # Short artifact labels are data, not prose.  A model occasionally
            # drops one character (for example ``Chênh lệch`` -> ``Chêh lệch``)
            # even though the exact label is present in the request.  Repair only
            # a unique, near-identical request phrase with the same word count;
            # lower-confidence differences remain untouched rather than guessing.
            if table_literal and value.strip() and len(value) <= 80 and len(value.split()) <= 8:
                ranked_labels = sorted(
                    (
                        (SequenceMatcher(None, normalized, folded(candidate)).ratio(), candidate)
                        for candidate in phrases
                        if len(candidate.split()) == len(value.split())
                        and abs(len(folded(candidate)) - len(normalized)) <= 2
                    ),
                    reverse=True,
                )
                if ranked_labels:
                    best_score, best_candidate = ranked_labels[0]
                    next_score = ranked_labels[1][0] if len(ranked_labels) > 1 else 0.0
                    if best_score >= 0.94 and best_score - next_score >= 0.08:
                        return best_candidate
            if suspicious(value) and not suspicious(request):
                word_count = len(value.split())
                signature = ascii_signature(value)
                ranked = sorted(
                    (
                        (
                            SequenceMatcher(None, signature, ascii_signature(candidate)).ratio(),
                            candidate,
                        )
                        for candidate in phrases
                        if len(candidate.split()) == word_count and ascii_signature(candidate)
                    ),
                    reverse=True,
                )
                if ranked and ranked[0][0] >= 0.8 and (
                    ranked[0][1] in strong_literals
                    or len(ranked) == 1
                    or ranked[0][0] - ranked[1][0] >= 0.12
                ):
                    return ranked[0][1]
                raise ValueError("Generated artifact contains unrecoverable text encoding")
            return value
        if isinstance(value, list):
            return [restore(item, table_literal=table_literal) for item in value]
        if isinstance(value, dict):
            return {
                key: restore(
                    item,
                    table_literal=table_literal or key in {"headers", "rows"},
                )
                for key, item in value.items()
            }
        return value

    payload = answer.model_dump(mode="python")
    payload["proposals"] = restore(payload["proposals"])
    return CreationAnswer.model_validate(payload)


def ground_unsourced_spreadsheet_preview(
    request: str, answer: CreationAnswer, *, has_source_data: bool
) -> CreationAnswer:
    """Keep an unsourced spreadsheet preview useful without fictitious records.

    A structural request such as "make an expense tracker" is permission to
    design columns and formulas, not evidence that particular transactions
    occurred. Leave sourced and explicitly supplied values untouched. A request
    for *sample* data may keep invented values, but must label them as examples.
    """

    sheets = [item for item in answer.proposals if isinstance(item, SpreadsheetProposal)]
    if not sheets or len(sheets) != len(answer.proposals) or has_source_data:
        return answer
    explicit_data, sample_requested = _sheet_request_data_flags(request)
    # "Tạo mẫu theo dõi" asks for a reusable blank template, not fabricated
    # transactions. Explicitly requested examples remain visibly illustrative.
    if sample_requested and not re.search(r"\b(?:mẫu trống|không có dữ liệu)\b", request, re.I):
        payload = answer.model_dump(mode="python")
        payload["answer"] = (
            "Các giá trị trong bản xem trước chỉ là dữ liệu minh họa, "
            "không phải giao dịch thật.\n\n"
            + answer.answer
        )
        for item in payload["proposals"]:
            spec = item["spreadsheet"]
            if "minh họa" not in spec["title"].casefold() and "dữ liệu mẫu" not in spec[
                "title"
            ].casefold():
                spec["title"] = (spec["title"][:170].rstrip() + " (Dữ liệu minh họa)")
        return CreationAnswer.model_validate(payload)

    if explicit_data:
        return answer

    payload = answer.model_dump(mode="python")
    previews: list[str] = []
    for item in payload["proposals"]:
        spec = item["spreadsheet"]
        title = re.sub(r"\b(?:19|20)\d{2}\b", "", spec["title"]).strip(" -–_")
        spec["title"] = (title[:170] or "Bảng dữ liệu") + " (Mẫu trống)"
        for tab in spec["tabs"]:
            headers = tab["headers"]
            amount_index = next(
                (
                    index
                    for index, header in enumerate(headers)
                    if re.search(
                        r"so tien|thanh tien|amount|gia tri|thuc chi",
                        unicodedata.normalize("NFKD", header)
                        .encode("ascii", errors="ignore")
                        .decode("ascii")
                        .casefold(),
                    )
                ),
                None,
            )
            blank = [None] * len(headers)
            tab["rows"] = [blank]
            tab["chart"] = None
            if amount_index is not None:
                total = [None] * len(headers)
                if amount_index != 0:
                    total[0] = "Tổng"
                total[amount_index] = SheetFormula(
                    function="SUM", column=amount_index, start_row=0, end_row=1
                )
                tab["rows"].append(total)
            escaped = [str(header).replace("|", "\\|") for header in headers]
            previews.append(
                "\n".join(
                    [
                        f"### {tab['title']}",
                        "| " + " | ".join(escaped) + " |",
                        "| " + " | ".join(["---"] * len(headers)) + " |",
                        "| " + " | ".join(["—"] * len(headers)) + " |",
                    ]
                )
            )
            if amount_index is not None:
                col = chr(ord("A") + amount_index)
                previews.append(
                    f"Công thức tổng dự kiến: `=SUM({col}2:{col}2)`; "
                    "hàng giao dịch hiện để trống."
                )
    payload["answer"] = (
        "## Bản xem trước — mẫu trống\n\n"
        + "\n\n".join(previews)
        + "\n\n- Chưa tạo bảng trên Google Sheets và chưa có giao dịch thật."
        "\n- Bạn có thể nhập khoản chi thật hoặc duyệt để tạo mẫu trống."
        "\n- Sau khi tạo, hệ thống cần đọc lại để đối chiếu trước khi báo hoàn tất."
    )
    return CreationAnswer.model_validate(payload)


def budget_tracker_template() -> CreationAnswer:
    """Build the reviewed one-click budget workbook without model variability."""

    rows = [
        [
            "Nhà ở",
            4_000_000,
            3_800_000,
            SheetRowFormula(
                operator="SUBTRACT", left_column=1, right_column=2, row=0
            ),
        ],
        [
            "Ăn uống",
            2_000_000,
            1_650_000,
            SheetRowFormula(
                operator="SUBTRACT", left_column=1, right_column=2, row=1
            ),
        ],
        [
            "Đi lại",
            800_000,
            620_000,
            SheetRowFormula(
                operator="SUBTRACT", left_column=1, right_column=2, row=2
            ),
        ],
        [
            "Học tập",
            1_200_000,
            950_000,
            SheetRowFormula(
                operator="SUBTRACT", left_column=1, right_column=2, row=3
            ),
        ],
        [
            "Tổng",
            SheetFormula(function="SUM", column=1, start_row=0, end_row=4),
            SheetFormula(function="SUM", column=2, start_row=0, end_row=4),
            SheetFormula(function="SUM", column=3, start_row=0, end_row=4),
        ],
    ]
    spec = SpreadsheetSpec(
        title="Veridra - Ngân sách tháng (Dữ liệu mẫu)",
        theme="finance",
        tabs=[
            SheetTab(
                title="Ngân sách",
                headers=[
                    "Nhóm chi phí",
                    "Ngân sách (VND)",
                    "Thực chi (VND)",
                    "Còn lại (VND)",
                ],
                rows=rows,
            )
        ],
    )
    return CreationAnswer(
        answer=(
            "Tôi đã chuẩn bị một bảng ngân sách mẫu gồm bốn nhóm chi phí, "
            "công thức tính số tiền còn lại theo từng dòng và hàng tổng tự động. "
            "Các số liệu đều là minh họa; hãy kiểm tra bản xem trước trước khi tạo file."
        ),
        proposals=[SpreadsheetProposal(kind="spreadsheet", spreadsheet=spec)],
    )


